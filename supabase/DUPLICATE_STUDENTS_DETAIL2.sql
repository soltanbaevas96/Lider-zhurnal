-- =====================================================================
--  Углублённая проверка 4 оставшихся пар: класс/школа (у одного ребёнка
--  не может отличаться) + реальные даты посещённых занятий по каждой
--  карточке. Если даты у пары СОВПАДАЮТ или идут вперемешку в одном
--  и том же периоде — это гарантированно один и тот же ребёнок с
--  раздвоенной историей. Если периоды НЕ пересекаются (чётко до/после
--  даты создания второй карточки) — это тоже похоже на one and the
--  same, просто переехал/перевёлся. Если посещения идут ПАРАЛЛЕЛЬНО
--  на разных днях недели годами — возможно, это правда разные треки.
--  ТОЛЬКО ЧТЕНИЕ. Один запрос — выполнить целиком, прислать результат.
-- =====================================================================
select
  s.full_name, s.id, s.office, s.lang, s.grade, s.school, s.created_at,
  (select string_agg(l.lesson_date::text, ', ' order by l.lesson_date)
     from attendance a join lessons l on l.id = a.lesson_id
     where a.student_id = s.id) as lesson_dates
from students s
where s.archived = false
  and s.full_name in (
    'Аскарова Аиша', 'Жылкайдаров Алтынбек', 'Кабыш Мансур', 'Мухансаликова Амира'
  )
order by s.full_name, s.created_at;

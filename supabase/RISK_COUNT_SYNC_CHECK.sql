-- =====================================================================
--  ПРОВЕРКА: почему на Дашборде "учеников в зоне риска" (40) не совпадает
--  со списком на вкладке «Риски» (28 к отработке + 2 внимание = 30).
--  Плюс — есть ли третье, ещё по-другому считающее место (get_notifications).
--  ТОЛЬКО ЧТЕНИЕ. Один запрос — выполнить целиком, прислать результат.
-- =====================================================================
select p.proname, pg_get_functiondef(p.oid) as definition
from pg_proc p
where p.pronamespace = 'public'::regnamespace
  and p.proname = 'get_notifications';

-- =====================================================================
--  ЛИДЕР+ · Разовая чистка №1: подтверждённые дубли учеников
--  (не миграция схемы — разовые операции с данными по решению владельца)
--
--  1) Два «призрака» без активных групп и почти без истории —
--     архивируем как обычное мягкое удаление (то же самое, что кнопка
--     «Удалить» в Управлении делает для одной карточки):
--       Кужахмет Алихан  cc6546d1-86a0-488d-b48b-d25606dcfecc
--       Торатхан Бислан  90011267-0a99-4e7f-aaee-185d9d52e96d
--
--  2) Сыздыкова Инабат — обе карточки реально использовались, но новая
--     (a1b28238…) была по ошибке добавлена в те же 3 группы, что и
--     старая (76e3ba42…), — отсюда дубль в списке группы 11КУС-3.
--     Убираем новую карточку из этих 3 групп, оставляем только там,
--     где она уникальна (11КУФ-1). Обе карточки остаются активными.
--
--  Выполнить в Supabase → SQL Editor ЦЕЛИКОМ.
-- =====================================================================

-- ---------- 1. Архивируем 2 подтверждённых «призрака» ----------
delete from student_groups where student_id in (
  'cc6546d1-86a0-488d-b48b-d25606dcfecc',
  '90011267-0a99-4e7f-aaee-185d9d52e96d'
);
update students set archived = true
where id in (
  'cc6546d1-86a0-488d-b48b-d25606dcfecc',
  '90011267-0a99-4e7f-aaee-185d9d52e96d'
);

-- ---------- 2. Сыздыкова Инабат: убрать дубль-карточку из общих групп ----------
delete from student_groups sg
using groups g
where sg.student_id = 'a1b28238-afd5-4285-b83c-efcbcabcefa2'
  and sg.group_id = g.id
  and g.name <> '11КУФ-1';

-- ---------- Проверка результата (должны видеть: первые два archived=true;
--            у Сыздыковой в groups — только 11КУФ-1) ----------
select s.id, s.full_name, s.archived,
       (select string_agg(g.name, ', ') from student_groups sg join groups g on g.id = sg.group_id
        where sg.student_id = s.id) as groups
from students s
where s.id in (
  'cc6546d1-86a0-488d-b48b-d25606dcfecc',
  '90011267-0a99-4e7f-aaee-185d9d52e96d',
  'a1b28238-afd5-4285-b83c-efcbcabcefa2'
);

-- =====================================================================
--  60. ИСПРАВИТЬ УНИКАЛЬНОСТЬ ГРУПП: (name, office), а не одно name
--
--  Обнаружено при импорте Камзины (59): попытка создать группу
--  "11 КММ-6" для офиса Камзина упала с ошибкой
--  "duplicate key value violates unique constraint uq_groups_name".
--
--  Проверка (pg_indexes) показала:
--    CREATE UNIQUE INDEX uq_groups_name ON public.groups USING btree (name)
--  То есть уникальность физически по ОДНОЙ колонке name — без office.
--  Это противоречит правилу, которое задокументировано в CLAUDE.md
--  и на котором построена вся логика проекта: "код группы уникален
--  в пределах ОДНОГО офиса, а не глобально". Получается, всё это
--  время база на самом деле не позволяла создать вторую группу с тем
--  же названием под другим офисом — то есть это баг схемы, возникший
--  раньше и никем не замеченный, а не баг логики импортов.
--
--  Что делает:
--   1. Удаляет старый чрезмерно строгий индекс uq_groups_name (по name).
--   2. Создаёт новый — по паре (name, office), и только среди АКТИВНЫХ
--      групп (where archived = false), чтобы архивные дубли (например,
--      объединённые миграцией 58) не мешали создать новую группу с
--      тем же именем.
--
--  Безопасно: снятие более строгого ограничения не может сломать
--  существующие данные — только разрешает то, что раньше случайно
--  запрещалось. Ничего не удаляется и не переименовывается.
--
--  После выполнения — заново запустить 59_import_kamzina_students.sql
--  (он идемпотентный, уже созданный ранее ученик "Ибраева Дамина" не
--  задвоится, остальные три создадутся вместе с группами).
-- =====================================================================

drop index if exists uq_groups_name;

create unique index if not exists uq_groups_name_office
  on groups (name, office)
  where archived = false;

-- ---------- Проверка: не терялись ли группы из-за этого же бага раньше ----------
-- Если тут есть строки — значит в более ранних запусках (54/55/56) для
-- каких-то учеников не создалась группа именно по этой причине, и их
-- стоит будет доимпортировать повторным запуском той же миграции.
select run_at, student_name, group_code, office, detail
from import_report_sept2026
where kind in ('error') and detail ilike '%uq_groups_name%'
order by run_at desc;

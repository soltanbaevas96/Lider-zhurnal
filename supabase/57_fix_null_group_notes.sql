-- =====================================================================
--  57. ПОЧИНИТЬ ГРУППЫ С ПУСТЫМ note (не показывались в «Управлении»)
--
--  Найдено: у части групп, созданных более ранним импортом (10 класс,
--  казахский язык, офисы Маргулана и Усолка), поле note оказалось
--  буквально NULL — сам предмет (subject_name) у них тоже NULL.
--  Страница «Управление» → «Группы» фильтрует список ПО ТЕКСТУ note
--  (ищет там название офиса и языка), а не по колонкам office/lang
--  напрямую — поэтому с пустым note группа физически есть в базе
--  (office/lang в колонках верные), но не проходит фильтр и не видна
--  на экране.
--
--  Что делает этот файл:
--   1. Точечно проставляет subject_name для 13 конкретных кодов групп
--      (Маргулана-каз и Усолка-каз, 10 класс) — предмет однозначно
--      известен из исходного Excel (см. 56_...sql), просто при более
--      раннем запуске не был записан.
--   2. Общей подчисткой пересобирает note в стандартном формате
--      "Предмет · Офис · Язык" из уже верных колонок subject_name/
--      office/lang — для ЛЮБОЙ группы, где note IS NULL, а не только
--      для этих 13 (на случай, если такая же болезнь где-то ещё).
--      Ничего не удаляет, трогает только строки с note IS NULL — уже
--      заполненные note не меняются.
--
--  Безопасно выполнять повторно (идемпотентно): на второй запуск
--  строк с note IS NULL уже не останется — ничего не изменится.
-- =====================================================================

-- ---------- 1. Точечно проставить subject_name по известным кодам ----------
update groups g set subject_name = v.subject
from (values
  ('10 КМБ-1', 'Маргулана', 'БИОЛОГИЯ'),
  ('10 КМГ-1', 'Маргулана', 'ГЕОГРАФИЯ'),
  ('10 КМИ-1', 'Маргулана', 'ҚАЗ ТАРИХ'),
  ('10 КМИ-2', 'Маргулана', 'ҚАЗ ТАРИХ'),
  ('10 КММ-1', 'Маргулана', 'МАТЕМ'),
  ('10 КМС-1', 'Маргулана', 'МАТ.САУАТ'),
  ('10 КМС-2', 'Маргулана', 'МАТ.САУАТ'),
  ('10 КМФ-1', 'Маргулана', 'ФИЗИКА'),
  ('10 КМХ-1', 'Маргулана', 'ХИМИЯ'),
  ('10 КУИ-1', 'Усолка', 'ҚАЗ ТАРИХ'),
  ('10 КУИ-2', 'Усолка', 'ҚАЗ ТАРИХ'),
  ('10 КУС-1', 'Усолка', 'МАТ.САУАТ'),
  ('10 КУС-2', 'Усолка', 'МАТ.САУАТ')
) as v(code, office, subject)
where g.archived = false
  and g.office = v.office
  and lower(trim(g.name)) = lower(trim(v.code))
  and g.subject_name is null;

-- ---------- 2. Пересобрать note там, где он NULL (любые группы) ----------
update groups
set note = trim(coalesce(subject_name,'') || ' · ' || coalesce(office,'') || ' · ' || coalesce(lang,''))
where archived = false
  and note is null;

-- ---------- Проверка результата ----------
select name, office, lang, subject_name, note
from groups
where office = 'Маргулана' and lang = 'каз' and name ilike '10 к%'
order by name;
